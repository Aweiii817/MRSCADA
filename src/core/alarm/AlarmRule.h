// ============================================================
// AlarmRule.h — 报警规则定义
// ============================================================
//
// 定义报警系统使用的核心数据结构与枚举：
//   - AlarmType：报警类型（高/高高/低/低低限、变化率、开关量、通信故障）
//   - AlarmPriority：报警优先级（严重/高/中/低）
//   - AlarmRule：报警规则结构体（描述一条报警的判定条件与属性）
//   - AlarmState：报警状态（未激活/激活/已确认/清除未确认）
//
// 报警规则（AlarmRule）由报警管理器（AlarmManager）加载与执行，
// 用于对实时位号数据进行越限/变化率/状态判定，产生报警事件。
// ============================================================

#pragma once

#include <string>    // std::string
#include <cstdint>   // uint8_t

// ------------------------------------------------------------
// AlarmType — 报警类型
// ------------------------------------------------------------
// 底层用 uint8_t 存储（节省内存），值从 0 开始递增。
// ------------------------------------------------------------
enum class AlarmType : uint8_t
{
    HIGH = 0,        // 高限报警（数值超过上限）
    HIGH_HIGH = 1,   // 高高限报警（数值远超上限，更严重）
    LOW = 2,         // 低限报警（数值低于下限）
    LOW_LOW = 3,     // 低低限报警（数值远低于下限，更严重）
    RATE_UP = 4,     // 变化率上升过快报警
    RATE_DOWN = 5,   // 变化率下降过快报警
    DIGITAL_ON = 6,  // 开关量置位报警（如阀门打开）
    DIGITAL_OFF = 7, // 开关量复位报警（如阀门关闭）
    COMM_FAULT = 8   // 通信故障报警（设备断线等）
};

// ------------------------------------------------------------
// AlarmPriority — 报警优先级
// ------------------------------------------------------------
// 用于区分报警的紧急程度，便于排序、过滤与显示。
// ------------------------------------------------------------
enum class AlarmPriority : uint8_t
{
    CRITICAL = 0,   // 严重（最高优先级，需立即处理）
    HIGH = 1,       // 高
    MEDIUM = 2,     // 中
    LOW = 3         // 低（最低优先级）
};

// ------------------------------------------------------------
// AlarmRule — 报警规则结构体
// ------------------------------------------------------------
// 描述一条报警规则：对哪个位号、按何种类型、以何种阈值判定，
// 触发后产生何种优先级的报警消息。
// ------------------------------------------------------------
struct AlarmRule
{
    std::string rule_id;            // 规则唯一标识
    std::string tag_name;           // 关联的位号名（如 "TE-101"）
    AlarmType type;                 // 报警类型（越限/变化率/开关量等）

    double limit = 0.0;             // 报警阈值（限值或变化率阈值）
    double hysteresis = 1.0;        // 回滞（死区），防止数值在阈值附近
                                    // 抖动导致报警反复触发/消除

    AlarmPriority priority = AlarmPriority::MEDIUM; // 报警优先级（默认中）

    std::string message;            // 报警消息模板（触发时显示给用户）
    bool enabled = true;            // 是否启用该规则（false 则忽略）
};

// ------------------------------------------------------------
// AlarmState — 报警状态
// ------------------------------------------------------------
// 表示一条报警当前所处的生命周期状态。
// ------------------------------------------------------------
enum class AlarmState : uint8_t
{
    INACTIVE = 0,        // 未激活（未触发）
    ACTIVE = 1,          // 已激活（正在报警，尚未确认）
    ACKNOWLEDGED = 2,    // 已确认（人工确认，但报警条件仍存在）
    CLEARED_UNACK = 3    // 已清除但未确认（条件消失，但尚未人工确认）
};
