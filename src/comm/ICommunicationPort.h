// ============================================================
// ICommunicationPort.h — 通信端口抽象接口
// ============================================================
//
// 本文件定义了通信模块的统一抽象接口，是整个系统与外部设备
// （PLC、智能仪表、仿真引擎等）进行数据交互的“契约层”。
//
// 上层（如 CommManager、各业务模块）只依赖 ICommunicationPort
// 这一抽象接口，而不关心底层具体是 Modbus RTU、Modbus TCP，
// 还是仿真端口。这样做的目的：
//   1. 屏蔽底层通信协议差异，使上层代码与具体实现解耦；
//   2. 便于新增/替换通信协议（例如将来接入 OPC UA、MQTT 等）；
//   3. 统一设备连接、读写、轮询的调用方式，降低维护成本。
//
// 本接口采用“纯虚函数 + 虚析构”的标准 C++ 多态设计：
//   任何具体的通信端口类都需要继承本接口并实现全部纯虚函数。
// ============================================================

#pragma once

#include <string>    // std::string：设备名、协议名、位号名等字符串
#include <vector>    // std::vector：批量读写标签时的容器
#include <cstdint>   // uint8_t：以明确的字节宽度表示设备状态

// ------------------------------------------------------------
// DeviceStatus — 设备连接状态枚举
// ------------------------------------------------------------
// 用于描述一个通信端口（设备）当前处于连接的哪个阶段。
// 上层 UI（如状态指示灯）可据此展示“未连接 / 连接中 / 已连接 /
// 故障”等不同状态。
// ------------------------------------------------------------
enum class DeviceStatus : uint8_t
{
    DISCONNECTED = 0,   // 未连接：尚未连接或已主动断开
    CONNECTING = 1,     // 正在连接：连接请求已发出，等待建立链路
    CONNECTED = 2,      // 已连接：链路建立成功，可进行正常数据交互
    FAULT = 3           // 连接故障：连接中断或发生异常（需重连）
};

// ------------------------------------------------------------
// DeviceConfig — 设备通信配置
// ------------------------------------------------------------
// 描述一个通信设备（端口）在连接与轮询时所需的配置参数。
// 定义成“带虚析构的基类”，允许不同协议扩展出各自专属的配置子类
// （例如 Modbus 配置可额外增加从站地址、寄存器映射等字段）。
// 当前基类只包含所有协议共有的通用配置项。
// ------------------------------------------------------------
struct DeviceConfig
{
    // 虚析构：保证通过基类指针删除子类对象时，能正确调用子类析构，
    // 避免资源泄漏。
    virtual ~DeviceConfig() = default;

    std::string device_name;    // 设备名称：用于标识和日志输出（如 "SimEngine"）
    std::string protocol_type;  // 协议类型：如 "modbus_rtu"、"simulation" 等
    int poll_interval_ms = 500; // 轮询间隔（毫秒）：每隔多久执行一次 poll()
    int timeout_ms = 1000;      // 超时时间（毫秒）：单次通信请求的等待上限
    int max_retries = 3;        // 最大重试次数：通信失败后允许自动重试的上限
};

// ------------------------------------------------------------
// ICommunicationPort — 通信端口抽象接口
// ------------------------------------------------------------
// 统一封装设备连接、标签读写与轮询等能力，是所有具体通信端口
// （如 ModbusRtuPort、ModbusTcpPort、SimPort）必须实现的接口。
// 各方法均为纯虚函数，强制子类提供具体实现。
// ------------------------------------------------------------
class ICommunicationPort
{
public:
    // 虚析构：允许通过基类指针安全地释放子类对象。
    virtual ~ICommunicationPort() = default;

    // 连接设备：
    //   根据传入的配置建立与设备的通信链路。
    // 参数：
    //   config — 设备通信配置（设备名、协议类型、超时等）。
    // 返回：
    //   true  — 连接成功；
    //   false — 连接失败。
    virtual bool connect(const DeviceConfig& config) = 0;

    // 断开设备连接：
    //   主动关闭与设备的通信链路，并释放相关资源。
    virtual void disconnect() = 0;

    // 检查设备是否已连接：
    // 返回：
    //   true  — 当前处于已连接状态；
    //   false — 未连接或连接中断。
    virtual bool isConnected() const = 0;

    // 获取设备连接状态：
    //   返回更细粒度的状态（未连接 / 连接中 / 已连接 / 故障）。
    // 返回：
    //   当前 DeviceStatus 枚举值。
    virtual DeviceStatus status() const = 0;

    // 读取单个标签值：
    //   根据位号读取设备的实时工程值。
    // 参数：
    //   tag_name — 要读取的位号（如 "TE-101"）。
    //   value    — 输出参数，读取成功后写入该位号的值。
    // 返回：
    //   true  — 读取成功；
    //   false — 读取失败（位号不存在、通信超时等）。
    virtual bool readTag(const std::string& tag_name, double& value) = 0;

    // 读取多个标签值：
    //   批量读取一组位号的实时值，通常比逐个读取更高效。
    // 参数：
    //   tag_names — 要读取的位号列表。
    //   values    — 输出参数，读取成功后按顺序写入对应的值；
    //               其大小与 tag_names 一致。
    // 返回：
    //   true  — 全部读取成功；
    //   false — 读取失败（可能部分失败）。
    virtual bool readTags(const std::vector<std::string>& tag_names,
        std::vector<double>& values) = 0;

    // 写入单个标签值：
    //   将一个值写入指定位号（用于下发控制命令或设定值）。
    // 参数：
    //   tag_name — 要写入的位号（如 "TV-101"）。
    //   value    — 要写入的值。
    // 返回：
    //   true  — 写入成功；
    //   false — 写入失败。
    virtual bool writeTag(const std::string& tag_name, double value) = 0;

    // 获取通信协议名称：
    //   返回当前端口所使用的协议名称，便于日志记录与界面展示。
    // 返回：
    //   协议名称字符串（如 "modbus_rtu"、"simulation"）。
    virtual std::string protocolName() const = 0;

    // 执行一次轮询：
    //   按配置批量读写所有已注册的标签，是定时数据采集的核心入口。
    // 返回：
    //   true  — 本轮轮询成功；
    //   false — 本轮轮询失败。
    virtual bool poll() = 0;
};
